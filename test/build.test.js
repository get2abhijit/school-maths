'use strict';
/** Tests the single-file bundle dist/mathe7.html without a browser (no dependencies). */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const root = path.join(__dirname, '..');
const { build } = require('../build.js');
const SRC = require('../src/index.js');

build();
const html = fs.readFileSync(path.join(root, 'dist', 'mathe7.html'), 'utf8');
const scripts = [...html.matchAll(/<script([^>]*)>([\s\S]*?)<\/script>/g)].map(m => ({ attrs: m[1], body: m[2] }));
const uiSources = ['ui/app.js', 'ui/views-practice.js', 'ui/views-other.js', 'ui/views-worksheet.js', 'ui/views-standort.js', 'ui/views-ka.js'].map(p => [p, fs.readFileSync(path.join(root, p), 'utf8')]);

test('build is deterministic', () => {
  build();
  assert.equal(fs.readFileSync(path.join(root, 'dist', 'mathe7.html'), 'utf8'), html);
});

test('bundle contains every part exactly once and no leftover markers', () => {
  assert.ok(!/\/\*@(CSS|CATALOG|EXAMS|ENGINE|APP|VIEWS)\*\//.test(html));
  assert.equal(scripts.length, 5, 'katex (external) + catalog + exams + engine + app');
  assert.match(html, /^<!doctype html>/i);
  assert.match(html, /<html lang="de">/);
  assert.match(html, /<meta charset="utf-8">/);
});

test("the bundle's engine runs in plain Node and matches src/ exactly", () => {
  const engineScript = scripts.find(s => s.body.includes('generated by tools/bundle-engine.js'));
  const sandbox = { self: {}, BigInt, console };
  sandbox.self = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(engineScript.body, sandbox);
  const B = sandbox.MathEngine;
  assert.equal(B.ENGINE_VERSION, SRC.ENGINE_VERSION);
  let n = 0;
  for (const t of SRC.TEMPLATES) for (const l of t.levels) for (const seed of [1, 2, 99, 123456789]) {
    const a = SRC.generateQuestion(t.id, seed, l), b = B.generateQuestion(t.id, seed, l);
    assert.equal(JSON.stringify(b), JSON.stringify(a), `${t.id} L${l} ${seed}`);
    const r = B.evaluateQuestion(b, B.canonicalInput(b.answer));
    assert.equal(r.status, 'correct');
    n++;
  }
  assert.ok(n >= 150);
  for (const skillId of SRC.skillsWithTemplates()) {
    const a = SRC.createSession({ skillId, count: 10, baseSeed: 5 }).session, b = B.createSession({ skillId, count: 10, baseSeed: 5 }).session;
    assert.equal(JSON.stringify(b), JSON.stringify(a));
  }
});

test('embedded exams equal exams.json', () => {
  const s = scripts.find(x => /id="exams-data"/.test(x.attrs));
  assert.ok(s, 'exams-data script');
  assert.deepEqual(JSON.parse(s.body), JSON.parse(fs.readFileSync(path.join(root, 'exams.json'), 'utf8')));
});

test('embedded catalog equals catalog.json', () => {
  const s = scripts.find(x => /id="catalog-data"/.test(x.attrs));
  assert.deepEqual(JSON.parse(s.body), JSON.parse(fs.readFileSync(path.join(root, 'catalog.json'), 'utf8')));
});

test('privacy: the only external resource is pinned KaTeX from cdnjs; no network APIs in the UI', () => {
  const urls = [...html.matchAll(/\b(?:src|href)\s*=\s*"(https?:[^"]+)"/g)].map(m => m[1]);
  assert.deepEqual(urls, ['https://cdnjs.cloudflare.com/ajax/libs/KaTeX/0.16.22/katex.min.js']);
  assert.ok(!/<link[^>]+stylesheet/i.test(html), 'no external stylesheets');
  assert.ok(!/@import|url\(\s*["']?https?:/i.test(html), 'no CSS imports or remote url()');
  for (const [p, src] of uiSources) {
    for (const bad of ['fetch(', 'XMLHttpRequest', 'sendBeacon', 'WebSocket', 'EventSource', 'importScripts', 'eval(', 'new Function', '.innerHTML', 'document.write', 'Math.random']) {
      assert.ok(!src.includes(bad), `${p} uses ${bad}`);
    }
  }
});

test('logic separation: the UI never reads solutions, distractors or curriculum ids', () => {
  const forbidden = ['.canonical', 'canonicalInput', '.distractors', 'answer.value', 'answer.correct', 'spec.value', 'spec.correct',
    '.solve(', 'checkForm', 'equivalent(', 'parseNumber', 'validateAnswer', 'templates.', 'REGISTRY'];
  for (const [p, src] of uiSources) {
    const code = src.replace(/\/\*[\s\S]*?\*\/|\/\/.*$/gm, '');
    for (const f of forbidden) assert.ok(!code.includes(f), `${p} contains ${f}`);
    assert.ok(!/['"]ch\d+\./.test(code), `${p} hard-codes a catalog id`);
  }
});

test('localStorage access in the UI is always guarded by try/catch', () => {
  const app = uiSources[0][1];
  const lines = app.split('\n').filter(l => l.includes('localStorage'));
  assert.ok(lines.length >= 3);
  for (const l of lines) assert.ok(/try \{|\/\/|\* /.test(l) || /^\s*try/.test(l), `unguarded: ${l.trim()}`);
  for (const [p, src] of uiSources.slice(1)) assert.ok(!src.includes('localStorage'), `${p} must use the helpers`);
});

test('every UI section exists and every route is linked', () => {
  for (const r of ['start', 'kapitel', 'ueben', 'arbeitsblaetter', 'wiederholen', 'fortschritt', 'ka']) {
    assert.match(html, new RegExp(`href="#${r}" data-route="${r}"`));
    assert.match(html, new RegExp(`VIEWS\\.${r} = function`));
  }
});

test("the bundle's engine builds byte-identical worksheets and layouts", () => {
  const engineScript = scripts.find(s => s.body.includes('generated by tools/bundle-engine.js'));
  const sandbox = { BigInt, console };
  sandbox.self = sandbox;
  vm.createContext(sandbox);
  vm.runInContext(engineScript.body, sandbox);
  const B = sandbox.MathEngine;
  for (const baseSeed of [1, 77, 2 ** 31]) {
    const spec = { skills: SRC.skillsWithTemplates(), levels: [1, 2, 3, 4], count: 20, baseSeed, keyMode: 'worked' };
    const a = SRC.createWorksheet(spec), b = B.createWorksheet(spec);
    assert.equal(JSON.stringify(b.worksheet), JSON.stringify(a.worksheet));
    assert.equal(JSON.stringify(B.worksheetLayout(b.worksheet, b.questions)), JSON.stringify(SRC.worksheetLayout(a.worksheet, a.questions)));
    assert.equal(B.loadWorksheet(JSON.parse(JSON.stringify(a.worksheet))).ok, true);
  }
});

test('print CSS: A4 page, page numbers, no question split, worksheet block is self-contained', () => {
  const css = fs.readFileSync(path.join(root, 'ui', 'styles.css'), 'utf8');
  const a = css.indexOf('/* @worksheet-css-start */'), b = css.indexOf('/* @worksheet-css-end */');
  assert.ok(a > 0 && b > a, 'worksheet CSS markers');
  const ws = css.slice(a, b);
  assert.match(ws, /@page\s*\{[^]*size:\s*A4/);
  assert.match(fs.readFileSync(path.join(root, 'ui', 'print-page.css'), 'utf8'), /@bottom-center[^}]*counter\(page\)/);
  assert.match(html, /<style id="page-css">(?:(?!<\/style>)[\s\S])*@bottom-center/);
  assert.match(ws, /\.ws-q\s*\{[^}]*break-inside:\s*avoid/);
  assert.match(ws, /page-break-inside:\s*avoid/);
  assert.ok(!ws.includes('var(--'), 'worksheet CSS must not depend on theme variables (standalone export)');
  assert.match(css, /@media print\s*\{[^}]*\.no-print/);
  assert.ok(!/url\(/.test(ws), 'no images/fonts in worksheet CSS');
  assert.ok(!/background(-image)?\s*:[^;]*gradient/.test(ws), 'Karo grid must not be a background (browsers drop backgrounds when printing)');
  assert.ok(!/<pattern/.test(fs.readFileSync(path.join(root, 'ui', 'views-worksheet.js'), 'utf8').replace(/\/\*[\s\S]*?\*\/|\/\/.*$/gm, '')), 'no SVG <pattern> in the grid');
});
